// A crate of crates.io's, or git's, in an app (ADR 0415): compiled by the
// app's rust-js where it can be, its JS committed in the app, in
// `rust-js/crates/<name>-<version>/`, and imported from there; one rust-js
// can't compile is its types alone, as rustc builds it, and a call into it
// is refused. A git repository stands in for crates.io: Cargo has a crate
// of either as it has the other, not the app's own.

import { beforeAll, expect, test } from "bun:test";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { runSync } from "./child";
import { node } from "./programs";
import { buildCompiler, compiler, fixture, root, run } from "./support";

beforeAll(buildCompiler, 600_000);

const cli = join(root, "tooling", "cli.js");
const build = (dir: string, ...args: string[]) => runSync([process.execPath, cli, "build", ...args], dir, 300_000, { RUST_JS_COMPILER: compiler });

/** A crate `name` at `version` in a git repository of its own, at `dir/name`, committed. */
function gitCrate(dir: string, name: string, version: string, source: string) {
  const crate = join(dir, name);
  mkdirSync(join(crate, "src"), { recursive: true });
  writeFileSync(join(crate, "Cargo.toml"), `[package]\nname = "${name}"\nversion = "${version}"\nedition = "2024"\n`);
  writeFileSync(join(crate, "src", "lib.rs"), source);
  const git = (...args: string[]) => runSync(["git", "-c", "user.name=t", "-c", "user.email=t@t", ...args], crate, 60_000);
  if (!existsSync(join(crate, ".git"))) expect(git("init", "-q").code).toBe(0);
  for (const args of [["add", "."], ["commit", "-q", "-m", version]]) expect(git(...args).code).toBe(0);
  return crate;
}

/** An app at `dir/app` that depends on `deps`, each a git crate's, and whose root is `source`. */
function app(dir: string, deps: Record<string, string>, source: string) {
  const at = join(dir, "app");
  mkdirSync(join(at, "src"), { recursive: true });
  const lines = Object.entries(deps).map(([name, crate]) => `${name} = { git = ${JSON.stringify(`file://${crate}`)} }`);
  writeFileSync(join(at, "Cargo.toml"), `[package]\nname = "app"\nversion = "0.0.0"\nedition = "2024"\n\n[dependencies]\n${lines.join("\n")}\n\n[workspace]\n`);
  writeFileSync(join(at, "src", "lib.rs"), source);
  return at;
}

const greet = 'pub fn hello(name: &str) -> String {\n    format!("Hello, {name}!")\n}\n';

test("a crate of crates.io's is compiled into the app, committed, and imported from there", () => {
  const dir = fixture("registry-compiled");
  const crate = gitCrate(dir, "greet", "0.1.0", greet);
  const at = app(dir, { greet: crate }, 'pub fn welcome() -> String {\n    greet::hello("Ada")\n}\n');
  const built = build(at);
  expect(built.stderr).toBe("");
  expect(built.code).toBe(0);
  // Its JS, named from its crate's directory, in the app's.
  const vendored = join(at, "rust-js", "crates", "greet-0.1.0", "src", "lib.js");
  expect(readFileSync(vendored, "utf8")).toStartWith("// Generated by rust-js from src/lib.rs. Do not edit.");
  expect(readFileSync(join(at, "src", "lib.js"), "utf8")).toContain('from "../rust-js/crates/greet-0.1.0/src/lib.js";');
  const program = `console.log((await import(${JSON.stringify(join(at, "src", "lib.js"))})).welcome());`;
  expect(run([node ?? "node", "--input-type=module", "--eval", program]).trim()).toBe("Hello, Ada!");
  // Committed, so checked as the app's own JS is.
  expect(build(at, "--check").code).toBe(0);
  writeFileSync(vendored, `${readFileSync(vendored, "utf8")}// edited\n`);
  const checked = build(at, "--check");
  expect(checked.code).not.toBe(0);
  expect(checked.stderr).toContain("rust-js/crates/greet-0.1.0/src/lib.js");
}, 600_000);

// Its version is in its directory's name: an upgrade writes the new one's,
// and the old one's goes, as any file a build no longer writes does.
test("a crate of crates.io's upgraded is the new version's JS, the old one's gone", () => {
  const dir = fixture("registry-upgraded");
  const crate = gitCrate(dir, "greet", "0.1.0", greet);
  const at = app(dir, { greet: crate }, 'pub fn welcome() -> String {\n    greet::hello("Ada")\n}\n');
  expect(build(at).code).toBe(0);
  gitCrate(dir, "greet", "0.2.0", greet.replace("Hello", "Hi"));
  expect(runSync(["cargo", "update", "-q", "--manifest-path", join(at, "Cargo.toml")], at, 120_000).code).toBe(0);
  const built = build(at);
  expect(built.stderr).toBe("");
  expect(existsSync(join(at, "rust-js", "crates", "greet-0.1.0"))).toBe(false);
  expect(readFileSync(join(at, "rust-js", "crates", "greet-0.2.0", "src", "lib.js"), "utf8")).toContain("Hi, ");
}, 600_000);

// One rust-js can't compile, a `transmute_copy`, which addresses memory
// (ADR 0390; an address read as a number no longer does, ADR 0562), is its
// types alone, as rustc builds it: an app that uses its types builds, and a
// call into it is refused, saying why its crate isn't compiled.
test("a crate of crates.io's rust-js can't compile is its types alone, and a call into it is refused", () => {
  const dir = fixture("registry-refused");
  const crate = gitCrate(dir, "addr", "0.1.0", "pub struct Byte(pub u8);\n\npub fn address(x: &Byte) -> u32 {\n    unsafe { std::mem::transmute_copy::<Byte, u8>(x) as u32 }\n}\n");
  const typed = app(dir, { addr: crate }, "pub fn first(bytes: &[addr::Byte]) -> u8 {\n    bytes[0].0\n}\n");
  const built = build(typed);
  expect(built.stderr).toBe("");
  expect(built.code).toBe(0);
  expect(existsSync(join(typed, "rust-js"))).toBe(false);
  writeFileSync(join(typed, "src", "lib.rs"), "pub fn at(b: &addr::Byte) -> u32 {\n    addr::address(b)\n}\n");
  const called = build(typed);
  expect(called.code).not.toBe(0);
  expect(called.stderr).toContain("addr::address");
  expect(called.stderr).toContain("addressable memory");
}, 600_000);

// One rust-js reads as rustc builds it, by its name, hashbrown and indexmap,
// whose maps are std's (ADRs 0423, 0424): never compiled by rust-js, even
// where it could be, so its own functions are refused where they're called.
test("a crate rust-js reads as rustc builds it isn't compiled, though it could be", () => {
  const dir = fixture("registry-read-as-rustc");
  const one = "pub fn one() -> u32 {\n    1\n}\n";
  const crates = { hashbrown: gitCrate(dir, "hashbrown", "0.17.1", one), indexmap: gitCrate(dir, "indexmap", "2.14.2", one) };
  const at = app(dir, crates, "pub fn maps() -> u32 {\n    hashbrown::one()\n}\n\npub fn ordered() -> u32 {\n    indexmap::one()\n}\n");
  const built = build(at);
  expect(built.code).not.toBe(0);
  expect(built.stderr).toContain("`hashbrown::one`");
  expect(built.stderr).toContain("`indexmap::one`");
  expect(existsSync(join(at, "rust-js", "crates"))).toBe(false);
  // Or one of the app's own, by its path.
  const manifest = readFileSync(join(at, "Cargo.toml"), "utf8");
  writeFileSync(join(at, "Cargo.toml"), manifest.replace(`git = ${JSON.stringify(`file://${crates.hashbrown}`)}`, `path = ${JSON.stringify(crates.hashbrown)}`));
  const own = build(at);
  expect(own.code).not.toBe(0);
  expect(own.stderr).toContain("`hashbrown::one`");
}, 600_000);

// One whose API rust-js writes, memchr (ADR 0529), is rustc's only where
// it's qualified, crates.io's, at a version rust-js writes it at: a fork of
// it, by its name and version, is its types alone, and a call into it is
// refused, saying which memchr to depend on, never lowered as memchr's.
test("a memchr that isn't crates.io's qualified one is refused where it's called", () => {
  const dir = fixture("registry-memchr-fork");
  const fork = gitCrate(dir, "memchr", "2.8.3", "pub fn memchr(needle: u8, haystack: &[u8]) -> Option<usize> {\n    haystack.iter().position(|&b| b == needle)\n}\n");
  const at = app(dir, { memchr: fork }, "pub fn first(text: &[u8]) -> Option<usize> {\n    memchr::memchr(b'o', text)\n}\n");
  const built = build(at);
  expect(built.code).not.toBe(0);
  expect(built.stderr).toContain("`memchr::memchr`");
  expect(built.stderr).toContain("isn't the memchr rust-js writes the JS of, crates.io's 2.8.3");
  expect(existsSync(join(at, "src", "lib.js"))).toBe(false);
}, 600_000);

