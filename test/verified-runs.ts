// A corpus case's runs, kept by what they ran (ADR 0567): the JS rust-js
// made of it, native Rust's output and end, the runtime modules the JS
// imports, the harness that runs and compares them, and the runtimes'
// versions. The same again, the runs would say the same, so they're not run
// again; the compiles are, each time, as they're what's checked of the
// compiler. Kept in `target/corpus-cache/<key>/passed`, as native programs
// are kept (`kept.ts`): each use marked, a week unused dropped.

import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";

import { markUsed } from "./kept";
import { node } from "./programs";
import { root, run, target } from "./support";

/** Where the corpus's verified runs are kept. */
export const verifiedRuns = join(target, "corpus-cache");

/** A key of `parts`, in their order, each whole: `["ab", "c"]` is not
 * `["a", "bc"]`. */
export function runKey(parts: (string | Uint8Array)[]): string {
  const hash = createHash("sha256");
  for (const part of parts) {
    hash.update(`${part.length}\0`).update(part);
  }
  return hash.digest("hex").slice(0, 32);
}

/** Whether runs of `key` were verified, in `cache`: they're marked used. */
export function verified(key: string, cache = verifiedRuns): boolean {
  const kept = join(cache, key, "passed");
  if (!existsSync(kept)) return false;
  markUsed(kept);
  return true;
}

/** Runs of `key` verified now, `note` saying whose. */
export function record(key: string, note: string, cache = verifiedRuns) {
  mkdirSync(join(cache, key), { recursive: true });
  writeFileSync(join(cache, key, "passed"), `${note}\n`);
}

/** The `.js` files under `dir`, sorted, but those under a directory of
 * `dir`'s named in `except`. */
export function jsFiles(dir: string, except: string[] = []): string[] {
  if (!existsSync(dir)) return [];
  return readdirSync(dir, { recursive: true, withFileTypes: true })
    .filter((entry) => entry.isFile() && entry.name.endsWith(".js"))
    .map((entry) => join(entry.parentPath, entry.name))
    .filter((file) => !except.some((name) => relative(dir, file).split("/")[0] === name))
    .sort();
}

/** What rust-js wrote under `dir`, each file's path from there and its
 * text, its header's path, the wrapper's in a folder of the run's own,
 * made the same. */
export function generatedTexts(dir: string, except: string[] = []): string[] {
  return jsFiles(dir, except).map(
    (file) =>
      `${relative(dir, file)}\0${readFileSync(file, "utf8").replace(/^\/\/ Generated by rust-js from .*\. Do not edit\.$/m, "// Generated by rust-js. Do not edit.")}`,
  );
}

/** What every case's runs share: the runtime modules, `@rust-js/runtime`'s
 * and `@rust-js/std`'s; the harness, from compiling to comparing; and
 * Node's version, Bun's, and Vite's, which bundles the JS as shipped.
 * Read once. */
let sharedKey: string | undefined;
export function shared(): string {
  if (sharedKey === undefined) {
    const harness = ["corpus.test.ts", "corpus-run.ts", "oracle.ts", "programs.ts", "child.ts", "verified-runs.ts"].map((file) => join(root, "test", file));
    const files = [...jsFiles(join(root, "runtime")), ...jsFiles(join(root, "std")), ...harness];
    const vite = JSON.parse(readFileSync(join(root, "node_modules", "vite", "package.json"), "utf8")).version;
    sharedKey = runKey([
      `node ${run([node ?? "node", "--version"]).trim()}`,
      `bun ${Bun.version}`,
      `vite ${vite}`,
      ...files.map((file) => `${relative(root, file)}\0${readFileSync(file, "utf8")}`),
    ]);
  }
  return sharedKey;
}
