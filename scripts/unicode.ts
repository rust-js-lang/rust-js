// Rust's Unicode tables for the runtime (#1888, ADR 1163): each question a
// `char` is asked, `is_alphabetic()`, `{:?}`'s escapes, `to_uppercase()`,
// answered as the pinned toolchain's std answers it, whatever Unicode
// version a JS engine has. scripts/unicode/main.rs, built by the checkout's
// toolchain, asks std of every `char`; this writes its answers as
// crates/rust-js-program/src/runtime/unicode_tables.js, which crates/rust-js-program/src/runtime/unicode.js reads.
//
//   bun scripts/unicode.ts [<file>]   # crates/rust-js-program/src/runtime/unicode_tables.js unless it's given
//
// Run it when the toolchain is bumped: test/unicode.test.ts fails until the
// tables are its std's.

import { spawnSync } from "node:child_process";
import { mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

const root = join(import.meta.dir, "..");

type Answers = {
  unicode: string;
  upper: [number, number[]][];
  lower: [number, number[]][];
} & Record<string, number[]>;

/** std's answers, of the checkout's toolchain. */
function answers(): { rust: string; answers: Answers } {
  const dir = mkdtempSync(join(tmpdir(), "rust-js-unicode-"));
  try {
    const exe = join(dir, "unicode");
    // In the checkout, whose rust-toolchain.toml rustup reads; its unstable
    // `is_cased` and `is_case_ignorable` too.
    const env = { ...process.env, RUSTC_BOOTSTRAP: "1" };
    const rust = spawnSync("rustc", ["--version"], { cwd: root, env, encoding: "utf8" }).stdout.trim();
    const built = spawnSync("rustc", ["-O", "--edition=2024", "-o", exe, join(import.meta.dir, "unicode", "main.rs")], { cwd: root, env, encoding: "utf8" });
    if (built.status !== 0) throw new Error(`scripts/unicode/main.rs didn't build:\n${built.stderr}`);
    const ran = spawnSync(exe, [], { encoding: "utf8", maxBuffer: 1 << 26 });
    if (ran.status !== 0) throw new Error(`scripts/unicode/main.rs failed:\n${ran.stderr}`);
    return { rust: rust.replace(/ \(.*\)$/, ""), answers: JSON.parse(ran.stdout) };
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

/** A set's boundaries, each a base-36 step from the one before. */
function set(bounds: number[]): string {
  let at = 0;
  return bounds
    .map((bound) => {
      const step = bound - at;
      at = bound;
      return step.toString(36);
    })
    .join(",");
}

/** A case map, each entry a step from the one before and what it becomes:
 * `step:offset` of one `char` an offset from it, `step:offset:count:stride`
 * of `count` of them, each `stride` after the last, and `step=a+b` of
 * `char`s, each base 36. */
function map(entries: [number, number[]][]): string {
  const tokens: string[] = [];
  let at = 0;
  for (let i = 0; i < entries.length; ) {
    const [from, to] = entries[i];
    const step = (from - at).toString(36);
    if (to.length !== 1) {
      tokens.push(`${step}=${to.map((c) => c.toString(36)).join("+")}`);
      at = from;
      i++;
      continue;
    }
    const offset = to[0] - from;
    // The run of those after it of the same offset, each the same stride on.
    let count = 1;
    const stride = i + 1 < entries.length ? entries[i + 1][0] - from : 0;
    while (
      i + count < entries.length &&
      entries[i + count][1].length === 1 &&
      entries[i + count][1][0] - entries[i + count][0] === offset &&
      entries[i + count][0] - entries[i + count - 1][0] === stride
    )
      count++;
    tokens.push(count === 1 ? `${step}:${offset.toString(36)}` : `${step}:${offset.toString(36)}:${count.toString(36)}:${stride.toString(36)}`);
    at = entries[i + count - 1][0];
    i += count;
  }
  return tokens.join(",");
}

/** The tables' module, of `rust`'s std's answers. */
export function tables(rust: string, given: Answers): string {
  const line = (name: string, doc: string, table: string) => `// ${doc}\nconst ${name} =\n  "${table}";\n`;
  return [
    `// Rust's Unicode tables, ${rust}'s std's, Unicode ${given.unicode} (#1888, ADR\n// 1163): what each \`char\` is, asked of std by scripts/unicode/main.rs.\n// Generated by \`bun scripts/unicode.ts\`. Do not edit.\n`,
    line("$unicodeAlphabetic", "`char::is_alphabetic`'s `char`s.", set(given.alphabetic)),
    line("$unicodeNumeric", "`char::is_numeric`'s.", set(given.numeric)),
    line("$unicodeUppercase", "`char::is_uppercase`'s.", set(given.uppercase)),
    line("$unicodeLowercase", "`char::is_lowercase`'s.", set(given.lowercase)),
    line("$unicodeWhitespace", "`char::is_whitespace`'s.", set(given.whitespace)),
    line("$unicodeCaseIgnorable", "What `str::to_lowercase`'s Final_Sigma skips, `char::is_case_ignorable`'s.", set(given.caseIgnorable)),
    line("$unicodeCased", "And what it asks of the `char` past them, `char::is_cased`'s.", set(given.cased)),
    line("$unicodeDebugEscaped", "What `{:?}` shows as `\\u{..}`, but the `char`s it names, `\\n` and the quotes.", set(given.debugEscaped)),
    line("$unicodeUpper", "`char::to_uppercase`'s mapping of each `char` it changes.", map(given.upper)),
    line("$unicodeLower", "`char::to_lowercase`'s.", map(given.lower)),
  ].join("\n");
}

if (import.meta.main) {
  const out = process.argv[2] ?? join(root, "crates", "rust-js-program", "src", "runtime", "unicode_tables.js");
  const { rust, answers: given } = answers();
  if (given.debugExtended.length > 0)
    throw new Error("this std's `{:?}` escapes a Grapheme_Extend `char` only where it's first: crates/rust-js-program/src/runtime/unicode.js asks no such table");
  writeFileSync(out, tables(rust, given));
}
