// Writes src/typed_arrays.rs: JS's typed arrays, each of one shape over its
// element type, and the buffers they view (ADR 0283). The shape is written
// here once, as Rust, not read from TypeScript's declarations: it's the
// crate's own binding, kept by hand in this file, of eleven classes alike.
//
//   bun builtins/typed_arrays.ts [out]   writes src/typed_arrays.rs, or `out`

const ELEMENTS: [string, string][] = [
  ["Int8Array", "i8"], ["Uint8Array", "u8"], ["Uint8ClampedArray", "u8"], ["Int16Array", "i16"],
  ["Uint16Array", "u16"], ["Int32Array", "i32"], ["Uint32Array", "u32"], ["Float32Array", "f32"],
  ["Float64Array", "f64"], ["BigInt64Array", "i64"], ["BigUint64Array", "u64"],
];
const BYTES: Record<string, number> = { i8: 1, u8: 1, i16: 2, u16: 2, i32: 4, u32: 4, f32: 4, f64: 8, i64: 8, u64: 8 };

import { snake } from "../scripts/rust-names";
const page = (path: string) => `https://developer.mozilla.org/docs/Web/JavaScript/Reference/Global_Objects/${path}`;

const out: string[] = [];
const line = (s = "") => out.push(s);

/** A required number parameter, `index: f64`, as any number that's an
 * `f64`, `index: impl Into<f64>`: `get(i)` of a `u32` too (ADR 0994,
 * amended). An optional one stays `Option<f64>`, whose `None` needs no type. */
const numbers = (signature: string) => signature.replace(/\b(\w+): f64(?=[,)])/g, "$1: impl Into<f64>");

/** A method: its doc, its JS, its Rust signature. */
const method = (doc: string, js: string, signature: string) => {
  signature = numbers(signature);
  line(`    /// ${doc}`);
  line(`    #[cfg_attr(rust_js, rust_js::link_name = ${JSON.stringify(js)})]`);
  line(`    pub fn ${signature} {`);
  line(`        unreachable!()`);
  line(`    }`);
  line();
};
/** A function of a module: a constructor or a static. */
const moduleFn = (doc: string, js: string, signature: string, variadic = false) => {
  signature = numbers(signature);
  line(`    /// ${doc}`);
  line(`    #[cfg_attr(rust_js, rust_js::link_name = ${JSON.stringify(js)})]`);
  if (variadic) line(`    #[cfg_attr(rust_js, rust_js::variadic)]`);
  line(`    pub fn ${signature} {`);
  line(`        unreachable!()`);
  line(`    }`);
  line();
};
const close = () => {
  if (out.at(-1) === "") out.pop();
};

line("//! JS's typed arrays and the buffers they view (ADR 0283): `Uint8Array`'s");
line("//! bytes, `Float64Array`'s numbers, each element a Rust number of its kind,");
line("//! a `BigInt64Array`'s an `i64`, the `BigInt` rust-js makes one (ADR 0086).");
line("//! Each callback is given an element and its index, `|x, _|` where it reads");
line("//! none, as TypeScript declares it, `(value, index) => ..`, and");
line("//! a comparator gives an `Ordering`, as ReScript's Stdlib has them.");
line("//! A number each takes or gives, a length, an index, an offset or an element,");
line("//! is TypeScript's `number`, an `f64`, which JS converts as it stores it, an");
line("//! `Int32Array`'s wrapping; a `BigInt64Array`'s element its `i64`. A number it");
line("//! must be given is any that's an `f64`, `impl Into<f64>` (ADR 0994, amended).");
line("//! Generated by `builtins/typed_arrays.ts`; edit the shape there.");
line();
line("// A binding's parameters are its JS function's: its body never runs.");
line("#![allow(unused_variables)]");
line();
line("use super::{Defined, JsError, JsObject, Rest, StructuredClone, Takes, Unknown};");
line("use core::marker::PhantomData;");
line("use core::ops::Deref;");

// ── Buffers ──────────────────────────────────────────────────────────────

line();
line(`/// [\`ArrayBuffer\`](${page("ArrayBuffer")}): bytes, which a typed array or a`);
line("/// `DataView` reads and writes.");
line('#[cfg_attr(rust_js, rust_js::types = "ArrayBuffer")]');
line("pub struct ArrayBuffer(PhantomData<JsObject>);");
line();
line("impl ArrayBuffer {");
method(`[\`buffer.byteLength\`](${page("ArrayBuffer/byteLength")}): how many bytes it has.`, "get byteLength", "byte_length(&self) -> f64");
method(`[\`buffer.maxByteLength\`](${page("ArrayBuffer/maxByteLength")}): how many it may grow to.`, "get maxByteLength", "max_byte_length(&self) -> f64");
method(`[\`buffer.resizable\`](${page("ArrayBuffer/resizable")}): whether \`resize\` changes it.`, "get resizable", "resizable(&self) -> bool");
method(`[\`buffer.detached\`](${page("ArrayBuffer/detached")}): whether \`transfer\` took its bytes.`, "get detached", "detached(&self) -> bool");
method(`[\`buffer.slice(begin, end)\`](${page("ArrayBuffer/slice")}): a copy of its bytes from \`begin\` to \`end\`, its start and its end where they aren't given.`, "slice", "slice(&self, begin: Option<f64>, end: Option<f64>) -> &'static ArrayBuffer");
method(`[\`buffer.resize(length)\`](${page("ArrayBuffer/resize")}): its length made \`length\`, or what it throws of a fixed one.`, "resize", "resize(&self, length: f64) -> Result<(), &'static JsError>");
method(`[\`buffer.transfer()\`](${page("ArrayBuffer/transfer")}): a new buffer of its bytes, this one detached.`, "transfer", "transfer(&self) -> &'static ArrayBuffer");
method(`[\`buffer.transferToFixedLength()\`](${page("ArrayBuffer/transferToFixedLength")}): \`transfer\`, a fixed length.`, "transferToFixedLength", "transfer_to_fixed_length(&self) -> &'static ArrayBuffer");
close();
line("}");
line();
line("pub mod array_buffer {");
line("    use super::*;");
line();
moduleFn(`[\`new ArrayBuffer(length)\`](${page("ArrayBuffer/ArrayBuffer")}): \`length\` bytes, each 0.`, "new ArrayBuffer", "new(length: f64) -> &'static ArrayBuffer");
moduleFn(`[\`ArrayBuffer.isView(value)\`](${page("ArrayBuffer/isView")}): whether \`value\`, any value, as TypeScript's \`any\`, is an [\`ArrayBufferView\`], a typed array or a \`DataView\` (ADR 0741).`, "ArrayBuffer.isView", "is_view(value: Option<&Unknown>) -> bool");
close();
line("}");
line();
line(`/// [\`SharedArrayBuffer\`](${page("SharedArrayBuffer")}): bytes workers share.`);
line('#[cfg_attr(rust_js, rust_js::types = "SharedArrayBuffer")]');
line("pub struct SharedArrayBuffer(PhantomData<JsObject>);");
line();
line("impl SharedArrayBuffer {");
method(`[\`buffer.byteLength\`](${page("SharedArrayBuffer/byteLength")}): how many bytes it has.`, "get byteLength", "byte_length(&self) -> f64");
method(`[\`buffer.growable\`](${page("SharedArrayBuffer/growable")}): whether \`grow\` changes it.`, "get growable", "growable(&self) -> bool");
method(`[\`buffer.maxByteLength\`](${page("SharedArrayBuffer/maxByteLength")}): how many it may grow to.`, "get maxByteLength", "max_byte_length(&self) -> f64");
method(`[\`buffer.grow(length)\`](${page("SharedArrayBuffer/grow")}): its length made \`length\`, or what it throws.`, "grow", "grow(&self, length: f64) -> Result<(), &'static JsError>");
method(`[\`buffer.slice(begin, end)\`](${page("SharedArrayBuffer/slice")}): a copy of its bytes from \`begin\` to \`end\`, its start and its end where they aren't given.`, "slice", "slice(&self, begin: Option<f64>, end: Option<f64>) -> &'static SharedArrayBuffer");
close();
line("}");
line();
line("pub mod shared_array_buffer {");
line("    use super::*;");
line();
moduleFn(`[\`new SharedArrayBuffer(length)\`](${page("SharedArrayBuffer/SharedArrayBuffer")}): \`length\` bytes, each 0.`, "new SharedArrayBuffer", "new(length: f64) -> &'static SharedArrayBuffer");
close();
line("}");

line();
line("/// A buffer a typed array or a `DataView` views, TypeScript's `ArrayBufferLike`:");
line("/// an `ArrayBuffer`, or a `SharedArrayBuffer`, as `Atomics` wants. A view is");
line("/// generic over it, `Int32Array<SharedArrayBuffer>`, its `buffer()` the one it is,");
line("/// as TypeScript's are; one of an `ArrayBuffer` unless said.");
line("///");
line("/// # Safety");
line("///");
line("/// It must be one of these.");
line("pub unsafe trait ArrayBufferLike {}");
line();
line("unsafe impl ArrayBufferLike for ArrayBuffer {}");
line("unsafe impl ArrayBufferLike for SharedArrayBuffer {}");

line();
line("/// TypeScript's [`ArrayBufferView`](https://developer.mozilla.org/docs/Web/JavaScript/Reference/Global_Objects/TypedArray):");
line("/// a typed array or a `DataView`, each of which derefs to it, a view of");
line("/// `B`'s bytes, of an `ArrayBuffer` unless said (ADR 0741). What a function");
line("/// of any view takes, `fn f(view: &ArrayBufferView)`, given a `&Uint8Array`.");
line("pub struct ArrayBufferView<B = ArrayBuffer>(PhantomData<JsObject>, PhantomData<B>);");
line();
line("// An object, never `undefined`, which a structured clone copies.");
line("unsafe impl<B> Defined for ArrayBufferView<B> {}");
line("unsafe impl<B> StructuredClone for ArrayBufferView<B> {}");
line();
line("impl<B> ArrayBufferView<B> {");
method(`[\`view.buffer\`](${page("TypedArray/buffer")}): the buffer it views.`, "get buffer", "buffer(&self) -> &'static B");
method(`[\`view.byteLength\`](${page("TypedArray/byteLength")}): how many bytes it views.`, "get byteLength", "byte_length(&self) -> f64");
method(`[\`view.byteOffset\`](${page("TypedArray/byteOffset")}): where in its buffer it starts.`, "get byteOffset", "byte_offset(&self) -> f64");
close();
line("}");

/** `name`'s `Deref` to the view it is: its `buffer`, `byteLength` and `byteOffset`. */
const view = (name: string) => {
  line();
  line(`impl<B> Deref for ${name}<B> {`);
  line("    type Target = ArrayBufferView<B>;");
  line();
  line("    fn deref(&self) -> &ArrayBufferView<B> {");
  line("        // Never runs: rust-js compiles this `Deref` to the object itself.");
  line("        unsafe { &*(self as *const Self as *const ArrayBufferView<B>) }");
  line("    }");
  line("}");
};

// ── DataView ─────────────────────────────────────────────────────────────

line();
line(`/// [\`DataView\`](${page("DataView")}): a buffer's bytes read and written as numbers`);
line("/// of any kind, at any offset, big-endian unless `little_endian` says.");
line('#[cfg_attr(rust_js, rust_js::types = "DataView")]');
line("pub struct DataView<B = ArrayBuffer>(PhantomData<JsObject>, PhantomData<B>);");
line();
view("DataView");
line();
line("impl<B> DataView<B> {");
for (const [kind, rust] of [["Int8", "i8"], ["Uint8", "u8"], ["Int16", "i16"], ["Uint16", "u16"], ["Int32", "i32"], ["Uint32", "u32"], ["Float32", "f32"], ["Float64", "f64"], ["BigInt64", "i64"], ["BigUint64", "u64"]]) {
  const one = BYTES[rust] === 1;
  const given = rust === "i64" || rust === "u64" ? rust : "f64";
  method(`[\`view.get${kind}(offset${one ? "" : ", littleEndian"})\`](${page(`DataView/get${kind}`)}): the ${rust} at \`offset\`.`, `get${kind}`, `${snake(`get${kind}`)}(&self, offset: f64${one ? "" : ", little_endian: bool"}) -> ${given}`);
  method(`[\`view.set${kind}(offset, value${one ? "" : ", littleEndian"})\`](${page(`DataView/set${kind}`)}): \`value\` written at \`offset\`.`, `set${kind}`, `${snake(`set${kind}`)}(&self, offset: f64, value: ${given}${one ? "" : ", little_endian: bool"})`);
}
close();
line("}");
line();
line("pub mod data_view {");
line("    use super::*;");
line();
method(`[\`new DataView(buffer, offset, length)\`](${page("DataView/DataView")}): a view of \`length\` bytes from \`offset\`, all of \`buffer\` where they aren't given.`, "new DataView", "new<B: ArrayBufferLike>(buffer: &B, offset: Option<f64>, length: Option<f64>) -> &'static DataView<B>");
method(`[\`value instanceof DataView\`](${page("DataView")}): whether \`value\`, any value, as TypeScript's \`any\`, is a \`DataView\` (ADR 0878).`, "instanceof DataView", "is(this: Option<&Unknown>) -> bool");
close();
line("}");

// ── The typed arrays ─────────────────────────────────────────────────────

line();
line("/// TypeScript's `ArrayLike<number>`, what a typed array's `set` and `from` take:");
line("/// numbers, each one a `T` takes ([`Takes`]), in a slice, an array or a `Vec`, or");
line("/// another typed array, `grown.set(event_log, None)`, as SchedulerProfiling");
line("/// grows its log. JS converts each as it stores it.");
line("pub trait ArrayLike<T: ?Sized> {}");
line();
line("impl<T: ?Sized + Takes<A>, A> ArrayLike<T> for [A] {}");
line("impl<T: ?Sized + Takes<A>, A, const N: usize> ArrayLike<T> for [A; N] {}");
line("impl<T: ?Sized + Takes<A>, A> ArrayLike<T> for Vec<A> {}");

for (const [name, e] of ELEMENTS) {
  const module = snake(name);
  const t = (m: string) => page(`TypedArray/${m}`);
  // A number it's given as an element: TypeScript's `number`, or a
  // `BigInt64Array`'s `bigint`, its `i64`.
  const n = e === "i64" || e === "u64" ? e : "f64";
  line();
  line(`/// [\`${name}\`](${page(name)}): ${BYTES[e]}-byte \`${e}\`s in a buffer, \`B\`.`);
  line(`#[cfg_attr(rust_js, rust_js::types = "${name}")]`);
  line(`pub struct ${name}<B = ArrayBuffer>(PhantomData<JsObject>, PhantomData<B>);`);
  line();
  line(`// An object, never \`undefined\`, which a structured clone copies.`);
  line(`unsafe impl<B> Defined for ${name}<B> {}`);
  line(`unsafe impl<B> StructuredClone for ${name}<B> {}`);
  line();
  line("// Its elements, spread, as rest arguments (ADR 0718), and as an array-like.");
  line(`impl<'a, T: ?Sized + Takes<${e}>, B> Rest<T> for &'a ${name}<B> {}`);
  line(`impl<T: ?Sized + Takes<${e}>, B> ArrayLike<T> for ${name}<B> {}`);
  view(name);
  line();
  line(`impl<B> ${name}<B> {`);
  method(`[\`array.length\`](${t("length")}): how many elements it has.`, "get length", "length(&self) -> f64");
  method(`[\`array.BYTES_PER_ELEMENT\`](${page(`TypedArray/BYTES_PER_ELEMENT`)}): ${BYTES[e]}.`, "get BYTES_PER_ELEMENT", "bytes_per_element(&self) -> f64");
  method(`\`array[index]\`: its element at \`index\`, \`None\` past its end.`, "get []", `get(&self, index: f64) -> Option<${n}>`);
  method(`\`array[index] = value\`: \`value\` written at \`index\`; past its end, nothing.`, "set []", `set_index(&self, index: f64, value: ${n})`);
  method(`[\`array.at(index)\`](${t("at")}): its element at \`index\`, from its end if negative.`, "at", `at(&self, index: f64) -> Option<${n}>`);
  method(`[\`array.set(items, offset)\`](${t("set")}): \`items\` written from \`offset\`, its start where it isn't given.`, "set", `set<A: ArrayLike<${n}> + ?Sized>(&self, items: &A, offset: Option<f64>)`);
  method(`[\`array.fill(value, start, end)\`](${t("fill")}): its elements from \`start\` to \`end\` \`value\`, each where they aren't given; itself.`, "fill", `fill(&self, value: ${n}, start: Option<f64>, end: Option<f64>) -> &'static ${name}<B>`);
  method(`[\`array.copyWithin(target, start, end)\`](${t("copyWithin")}): its elements from \`start\` to \`end\`, its end where it isn't given, copied to \`target\`; itself.`, "copyWithin", `copy_within(&self, target: f64, start: f64, end: Option<f64>) -> &'static ${name}<B>`);
  method(`[\`array.reverse()\`](${t("reverse")}): its elements reversed, in place; itself.`, "reverse", `reverse(&self) -> &'static ${name}<B>`);
  method(`[\`array.sort(compare)\`](${t("sort")}): its elements in order, in place, or in \`compare\`'s, \`a.cmp(&b)\` as Rust sorts, an \`Ordering\` JS reads as -1, 0 or 1 (ADR 0057); itself.`, "sort", `sort(&self, compare: Option<Box<dyn FnMut(${n}, ${n}) -> core::cmp::Ordering>>) -> &'static ${name}<B>`);
  method(`[\`array.toSorted(compare)\`](${t("toSorted")}): a sorted copy, or one in \`compare\`'s order.`, "toSorted", `to_sorted(&self, compare: Option<Box<dyn FnMut(${n}, ${n}) -> core::cmp::Ordering>>) -> &'static ${name}`);
  method(`[\`array.toReversed()\`](${t("toReversed")}): a reversed copy.`, "toReversed", `to_reversed(&self) -> &'static ${name}`);
  method(`[\`array.with(index, value)\`](${t("with")}): a copy with \`value\` at \`index\`, or what it throws past its end.`, "with", `with(&self, index: f64, value: ${n}) -> Result<&'static ${name}, &'static JsError>`);
  method(`[\`array.slice(start, end)\`](${t("slice")}): a copy of its elements from \`start\` to \`end\`, its start and its end where they aren't given.`, "slice", `slice(&self, start: Option<f64>, end: Option<f64>) -> &'static ${name}`);
  method(`[\`array.subarray(start, end)\`](${t("subarray")}): a view of its elements from \`start\` to \`end\`, its start and its end where they aren't given, sharing its buffer.`, "subarray", `subarray(&self, start: Option<f64>, end: Option<f64>) -> &'static ${name}<B>`);
  method(`[\`array.includes(value, from)\`](${t("includes")}): whether it has \`value\`, NaN too, from \`from\` on.`, "includes", `includes(&self, value: ${n}, from: Option<f64>) -> bool`);
  method(`[\`array.indexOf(value, from)\`](${t("indexOf")}): where it first has \`value\`, from \`from\` on, or -1.`, "indexOf", `index_of(&self, value: ${n}, from: Option<f64>) -> f64`);
  method(`[\`array.lastIndexOf(value, from)\`](${t("lastIndexOf")}): where it last has \`value\`, up to \`from\`, or -1.`, "lastIndexOf", `last_index_of(&self, value: ${n}, from: Option<f64>) -> f64`);
  method(`[\`array.every(test)\`](${t("every")}): whether each element passes \`test\`.`, "every", `every(&self, test: impl FnMut(${n}, f64) -> bool + 'static) -> bool`);
  method(`[\`array.some(test)\`](${t("some")}): whether an element passes \`test\`.`, "some", `some(&self, test: impl FnMut(${n}, f64) -> bool + 'static) -> bool`);
  method(`[\`array.filter(test)\`](${t("filter")}): a copy of the elements that pass \`test\`.`, "filter", `filter(&self, test: impl FnMut(${n}, f64) -> bool + 'static) -> &'static ${name}`);
  method(`[\`array.find(test)\`](${t("find")}): the first element that passes \`test\`.`, "find", `find(&self, test: impl FnMut(${n}, f64) -> bool + 'static) -> Option<${n}>`);
  method(`[\`array.findIndex(test)\`](${t("findIndex")}): where the first that passes \`test\` is, or -1.`, "findIndex", `find_index(&self, test: impl FnMut(${n}, f64) -> bool + 'static) -> f64`);
  method(`[\`array.findLast(test)\`](${t("findLast")}): the last element that passes \`test\`.`, "findLast", `find_last(&self, test: impl FnMut(${n}, f64) -> bool + 'static) -> Option<${n}>`);
  method(`[\`array.findLastIndex(test)\`](${t("findLastIndex")}): where the last that passes \`test\` is, or -1.`, "findLastIndex", `find_last_index(&self, test: impl FnMut(${n}, f64) -> bool + 'static) -> f64`);
  method(`[\`array.forEach(f)\`](${t("forEach")}): \`f\` of each element, in order.`, "forEach", `for_each(&self, f: impl FnMut(${n}, f64) + 'static)`);
  method(`[\`array.map(f)\`](${t("map")}): a typed array of what \`f\` makes of each element.`, "map", `map(&self, f: impl FnMut(${n}, f64) -> ${n} + 'static) -> &'static ${name}`);
  method(`[\`array.reduce(f, initial)\`](${t("reduce")}): \`f\` of each element and what it made of the ones before, from \`initial\`.`, "reduce", `reduce<A>(&self, f: impl FnMut(A, ${n}, f64) -> A + 'static, initial: A) -> A`);
  method(`[\`array.reduceRight(f, initial)\`](${t("reduceRight")}): \`reduce\`, from its end.`, "reduceRight", `reduce_right<A>(&self, f: impl FnMut(A, ${n}, f64) -> A + 'static, initial: A) -> A`);
  method(`[\`array.join(separator)\`](${t("join")}): its elements as text, \`separator\` between, \`,\` where it isn't given.`, "join", "join(&self, separator: Option<&str>) -> String");
  method(`[\`array.toString()\`](${t("toString")}): its elements as text, \`,\` between.`, "toString", "to_string(&self) -> String");
  method(`[\`array.toLocaleString()\`](${t("toLocaleString")}): its elements as the user's locale writes them.`, "toLocaleString", "to_locale_string(&self) -> String");
  method(`[\`array.valueOf()\`](${t("valueOf")}): itself.`, "valueOf", `value_of(&self) -> &'static ${name}<B>`);
  method(`[\`array.keys()\`](${t("keys")}): its indices, a JS iterator (ADR 0140).`, "keys", "keys(&self) -> Box<dyn Iterator<Item = f64>>");
  method(`[\`array.values()\`](${t("values")}): its elements, a JS iterator.`, "values", `values(&self) -> Box<dyn Iterator<Item = ${n}>>`);
  method(`[\`array.entries()\`](${t("entries")}): its indices and elements, a JS iterator.`, "entries", `entries(&self) -> Box<dyn Iterator<Item = (f64, ${n})>>`);
  close();
  line("}");
  line();
  line(`pub mod ${module} {`);
  line("    use super::*;");
  line();
  line(`    /// [\`${name}.BYTES_PER_ELEMENT\`](${page("TypedArray/BYTES_PER_ELEMENT")}): how many bytes an element is.`);
  line(`    pub const BYTES_PER_ELEMENT: f64 = ${BYTES[e]}.0;`);
  line();
  moduleFn(`[\`${name}.prototype\`](${page(`${name}`)}): what each \`${name}\` inherits from, its methods, whose prototype in turn is every typed array's, as React's \`getPrototypeOf(Uint32Array.prototype).constructor\` reads (ADR 0878).`, `get ${name}.prototype`, `prototype() -> &'static ${name}`);
  moduleFn(`[\`new ${name}(length)\`](${page(`${name}/${name}`)}): \`length\` elements, each 0.`, `new ${name}`, `new(length: f64) -> &'static ${name}`);
  moduleFn(`[\`${name}.from(items)\`](${t("from")}): a typed array of \`items\`.`, `${name}.from`, `from<A: ArrayLike<${n}> + ?Sized>(items: &A) -> &'static ${name}`);
  moduleFn(`[\`${name}.of(..items)\`](${t("of")}): a typed array of \`items\`.`, `${name}.of`, `of(items: impl Rest<${n}>) -> &'static ${name}`, true);
  method(`[\`new ${name}(buffer, byteOffset, length)\`](${page(`${name}/${name}`)}): a view of \`length\` elements from \`byte_offset\`, all of \`buffer\` where they aren't given.`, `new ${name}`, `new_with_buffer<B: ArrayBufferLike>(buffer: &B, byte_offset: Option<f64>, length: Option<f64>) -> &'static ${name}<B>`);
  close();
  line("}");
}

