// The Rust every program of the iterator tables begins with (ADR 1090):
// the items, which print as they're dropped and cloned, the accumulators,
// the crate's iterators' helpers and the runner that runs each case under
// `catch_unwind`. Split from test/iterator-matrix.ts by concept, as a test
// file is at most 1500 lines.

export const prelude = `// Generated by test/iterator-matrix.ts (ADR 1090). Each case prints its
// name, what it prints and drops, and whether it panicked.
use std::collections::{HashMap, HashSet};
use std::iter::Sum;
use std::panic::catch_unwind;
use std::sync::atomic::{AtomicU32, Ordering};

/** The item whose drop panics, or none. */
static BOOM: AtomicU32 = AtomicU32::new(0);

#[derive(Debug, PartialEq, Eq, Hash, PartialOrd, Ord)]
struct D(u32);

impl Drop for D {
    fn drop(&mut self) {
        println!("drop {}", self.0);
        if self.0 == BOOM.load(Ordering::Relaxed) {
            BOOM.store(0, Ordering::Relaxed);
            panic!("drop");
        }
    }
}

impl Clone for D {
    fn clone(&self) -> D {
        println!("clone {}", self.0);
        D(self.0)
    }
}

/** An accumulator, which prints as it's dropped. */
struct Acc(u32);

impl Drop for Acc {
    fn drop(&mut self) {
        println!("drop acc {}", self.0);
    }
}

/** What \`sum\` makes, which prints as it's dropped. */
struct Total(u32);

impl Drop for Total {
    fn drop(&mut self) {
        println!("drop total {}", self.0);
    }
}

impl Sum<D> for Total {
    fn sum<I: Iterator<Item = D>>(iter: I) -> Total {
        iter.fold(Total(0), |mut t, d| {
            t.0 += d.0;
            t
        })
    }
}

impl<'a> Sum<&'a D> for Total {
    fn sum<I: Iterator<Item = &'a D>>(iter: I) -> Total {
        iter.fold(Total(0), |mut t, d| {
            t.0 += d.0;
            t
        })
    }
}

impl Sum<u32> for Total {
    fn sum<I: Iterator<Item = u32>>(iter: I) -> Total {
        Total(iter.fold(0, |t, n| t + n))
    }
}

impl<'a> Sum<&'a u32> for Total {
    fn sum<I: Iterator<Item = &'a u32>>(iter: I) -> Total {
        Total(iter.fold(0, |t, n| t + n))
    }
}

/** An item's number. */
trait V {
    fn v(&self) -> u32;
}

impl V for D {
    fn v(&self) -> u32 {
        self.0
    }
}

impl V for u32 {
    fn v(&self) -> u32 {
        *self
    }
}

impl V for usize {
    fn v(&self) -> u32 {
        *self as u32
    }
}

impl<T: V + ?Sized> V for &T {
    fn v(&self) -> u32 {
        (**self).v()
    }
}

impl<A: V, B: V> V for (A, B) {
    fn v(&self) -> u32 {
        self.0.v() * 1000 + self.1.v()
    }
}

fn ds() -> Vec<D> {
    vec![D(1), D(2), D(3), D(4), D(5)]
}

/** A crate iterator's item \`n\`, or its panic. */
fn yielded(n: u32, boom: u32) -> Option<D> {
    if n == boom {
        panic!("next");
    }
    Some(D(n))
}

/** The items' numbers, by an index, not an iterator. */
fn show<T: V>(items: &[T]) -> String {
    let mut out = String::new();
    let mut i = 0;
    while i < items.len() {
        out.push_str(&format!(" {}", items[i].v()));
        i += 1;
    }
    out
}

/** What a function that asks the hint of what it's given gives (#1323). */
fn hint_of<I: Iterator>(it: I) -> (usize, Option<usize>) {
    it.size_hint()
}

fn sorted<T: Ord>(mut items: Vec<T>) -> Vec<T> {
    items.sort();
    items
}

fn run(name: &str, case: fn()) {
    println!("case {name}");
    let ended = catch_unwind(case);
    BOOM.store(0, Ordering::Relaxed);
    match ended {
        Ok(()) => println!("ended"),
        Err(payload) => println!("panicked: {}", payload.downcast_ref::<&str>().copied().unwrap_or("?")),
    }
}
`;
