// A crate's root of its `mod`s and a `pub use` of a type alone has no JS of
// its own, and still a `.d.ts` that re-exports the type (#2399, ADR 1005):
// a type it re-exports is a type it exports, whether one `use` names it, a
// glob gives it, or a library defines it. A TypeScript caller imports the
// type from the crate's root, as a Rust caller `use`s it from there.

import { beforeAll, expect, test } from "bun:test";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { buildReact, compiler, fixture, run, target } from "./support";
import { typeChecked } from "./type-checked";

beforeAll(buildReact, 600_000);

const js = ["--extern", `js=${join(target, "libjs.rmeta")}`, "-L", target];

/** `dep`, a library, and `app`, a crate that uses it, compiled in `dir`,
 * each with its declarations. */
function compiled(dir: string, app: string) {
  mkdirSync(join(dir, "dep"), { recursive: true });
  writeFileSync(join(dir, "dep.rs"), `pub struct Coin {
    pub cents: u32,
}

pub fn coin(cents: u32) -> Coin {
    Coin { cents }
}
`);
  run([compiler, "--declarations", join(dir, "dep.rs"), "-o", join(dir, "dep", "lib.js"), "--library", "--manifest", join(dir, "dep", "lib.manifest.json"),
    "--", "--crate-name", "dep", `--emit=metadata=${join(dir, "libdep.rmeta")}`, ...js]);
  writeFileSync(join(dir, "app.rs"), app);
  run([compiler, "--declarations", join(dir, "app.rs"), "-o", join(dir, "app", "lib.js"), "--dependency", join(dir, "dep", "lib.manifest.json"),
    "--", "--crate-name", "app", "--extern", `dep=${join(dir, "libdep.rmeta")}`, "-L", dir, ...js]);
}

const cases: { name: string; app: string; reexports: string[]; caller: string }[] = [
  {
    name: "one",
    app: `mod money {
    pub struct Money {
        pub cents: u32,
    }

    pub fn zero() -> Money {
        Money { cents: 0 }
    }
}

pub use money::Money;
`,
    reexports: ['export type { Money } from "./money.js";'],
    caller: 'import type { Money } from "./app/lib.js";\n\nexport const price: Money = { cents: 5 };\nexport const wrong: Money = { cents: "5" };\n',
  },
  {
    // A glob of a function and a type: the function's re-export, as
    // before, and the type's beside it.
    name: "glob",
    app: `mod shapes {
    pub enum Kind {
        Round,
        Square,
    }

    pub fn round() -> Kind {
        Kind::Round
    }
}

pub use shapes::*;
`,
    reexports: ['export { round } from "./shapes.js";', 'export type { Kind } from "./shapes.js";'],
    caller: 'import { round, type Kind } from "./app/lib.js";\n\nexport const kind: Kind = round();\nexport const wrong: Kind = "Oval";\n',
  },
  {
    // A glob of a module of types alone, its `.d.ts` alone.
    name: "glob-of-types",
    app: `mod shapes {
    pub enum Kind {
        Round,
        Square,
    }

    pub type Size = u32;
}

pub use shapes::*;
`,
    reexports: ['export type { Kind, Size } from "./shapes.js";'],
    caller: 'import type { Kind, Size } from "./app/lib.js";\n\nexport const kind: Kind = "Round";\nexport const size: Size = 3;\nexport const wrong: Size = "3";\n',
  },
  {
    // A glob of a type and a function of its name, which writes JS of that
    // name: the function's re-export alone, as one `use` of it is, where
    // the type's beside it would export the name twice (`alone`, #2399).
    name: "glob-of-a-type-and-its-value",
    app: `mod length {
    pub struct Meters {
        pub value: f64,
    }

    #[allow(non_snake_case)]
    pub fn Meters(value: f64) -> Meters {
        Meters { value }
    }
}

pub use length::*;
`,
    reexports: ['export { Meters } from "./length.js";'],
    caller: 'import { Meters } from "./app/lib.js";\n\nexport const length: Meters = Meters(3);\nexport const wrong: Meters = { value: "3" };\n',
  },
  {
    name: "library",
    app: "pub use dep::Coin;\n",
    reexports: ['export type { Coin } from "../dep/lib.js";'],
    caller: 'import type { Coin } from "./app/lib.js";\n\nexport const coin: Coin = { cents: 5 };\nexport const wrong: Coin = { cents: "5" };\n',
  },
];

for (const { name, app, reexports, caller } of cases) {
  test(`a root that re-exports a type alone has its .d.ts: ${name}`, () => {
    const dir = fixture(`declarations-type-reexports-${name}`);
    compiled(dir, app);
    // The root's JS, of nothing, as any root's (ADR 1005), and its `.d.ts`.
    expect(existsSync(join(dir, "app", "lib.js"))).toBe(true);
    const declarations = readFileSync(join(dir, "app", "lib.d.ts"), "utf8");
    expect(declarations.split("\n").filter(Boolean)).toEqual(["// Generated by rust-js from app.rs. Do not edit.", ...reexports]);
    // A TypeScript caller imports each from the root, held to its type:
    // the last line alone is wrong.
    writeFileSync(join(dir, "caller.ts"), caller);
    const errors = typeChecked(dir, "caller.ts", {});
    expect(errors).toHaveLength(1);
    expect(errors[0]).toContain(`caller.ts(${caller.trimEnd().split("\n").length},`);
  });
}
