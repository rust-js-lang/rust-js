// @rust-js/typescript (ADR 0206): TypeScript's own parser and printer, and
// the model of declarations between them, which rust-js writes its .d.ts
// with and reads a package's declarations with.

import { expect, test } from "bun:test";
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { checkedMembers, open } from "@rust-js/typescript";
import { fixture, root } from "./support";
import { underLoad } from "../scripts/timing";

const declarations = `import type { ReactNode } from "react";

export interface AnchorProps<T> extends HTMLProps<T>, Aria {
    href?: string | undefined;
    readonly "aria-label"?: string;
    [prop: string]: unknown;
    onClick?(event: T, ...rest: number[]): void;
}

export type Size = "md" | "lg" | 1 | true | null;

export function Link<C extends ReactNode>(props: AnchorProps<C>, children?: readonly (string | number)[]): ReactNode;

export const Icon: [
    boolean,
    {
        id: string;
    }
];

export const assign: typeof Object.assign;

declare namespace React {
    type Handler = (event: string) => void;
}

export default Link;
`;

test("read gives a file's declarations, by TypeScript's own parser", async () => {
  const dir = fixture("typescript-read");
  const file = join(dir, "anchor.d.ts");
  writeFileSync(file, declarations);
  const ts = await open([file]);
  try {
    const { declarations: read } = await ts.read(file);
    expect(read.map((d) => d.kind)).toEqual(["import", "interface", "type", "function", "const", "const", "namespace", "export-default"]);
    expect(read[0]).toEqual({ kind: "import", from: "react", names: ["ReactNode"], typeOnly: true });
    expect(read[1]).toEqual({
      kind: "interface",
      name: "AnchorProps",
      exported: true,
      declare: false,
      typeParameters: [{ name: "T" }],
      extends: [
        { kind: "reference", name: "HTMLProps", args: [{ kind: "reference", name: "T", args: [] }] },
        { kind: "reference", name: "Aria", args: [] },
      ],
      members: [
        {
          kind: "property",
          name: "href",
          optional: true,
          readonly: false,
          type: { kind: "union", types: [{ kind: "keyword", keyword: "string" }, { kind: "keyword", keyword: "undefined" }] },
        },
        { kind: "property", name: "aria-label", optional: true, readonly: true, type: { kind: "keyword", keyword: "string" } },
        { kind: "index", parameter: "prop", key: { kind: "keyword", keyword: "string" }, type: { kind: "keyword", keyword: "unknown" } },
        {
          kind: "method",
          name: "onClick",
          optional: true,
          typeParameters: [],
          params: [
            { name: "event", optional: false, rest: false, type: { kind: "reference", name: "T", args: [] } },
            { name: "rest", optional: false, rest: true, type: { kind: "array", element: { kind: "keyword", keyword: "number" }, readonly: false } },
          ],
          returns: { kind: "keyword", keyword: "void" },
        },
      ],
    });
    // A global's type, its overloads too (ADR 0622).
    expect(read[5]).toMatchObject({ name: "assign", type: { kind: "typeof", name: "Object.assign" } });
    expect(read[3]).toMatchObject({ typeParameters: [{ name: "C", constraint: { kind: "reference", name: "ReactNode", args: [] } }] });
    expect(read[2]).toMatchObject({
      type: {
        kind: "union",
        types: [
          { kind: "literal", value: "md" },
          { kind: "literal", value: "lg" },
          { kind: "literal", value: 1 },
          { kind: "literal", value: true },
          { kind: "keyword", keyword: "null" },
        ],
      },
    });
    // Printed by TypeScript, it's the file again, and read again, the model.
    const printed = await ts.print({ declarations: read });
    expect(printed).toBe(declarations);
    const again = join(dir, "again.d.ts");
    writeFileSync(again, printed);
    const reopened = await open([again]);
    try {
      expect((await reopened.read(again)).declarations).toEqual(read);
    } finally {
      await reopened.close();
    }
  } finally {
    await ts.close();
  }
});

test("print writes a model as TypeScript prints it, a header first", async () => {
  const ts = await open();
  try {
    const printed = await ts.print({
      header: "// Generated by rust-js from lib.rs. Do not edit.",
      declarations: [
        { kind: "import", from: "react", names: ["NamedExoticComponent", "ReactNode"], typeOnly: true },
        {
          kind: "interface",
          name: "Props",
          exported: true,
          declare: false,
          typeParameters: [],
          extends: [{ kind: "reference", name: "Omit", args: [{ kind: "reference", name: "Anchor", args: [] }, { kind: "literal", value: "href" }] }],
          members: [{ kind: "property", name: "size", optional: true, readonly: false, type: { kind: "array", element: { kind: "union", types: [{ kind: "keyword", keyword: "string" }, { kind: "keyword", keyword: "undefined" }] }, readonly: false } }],
        },
        { kind: "export-default", name: "Props" },
      ],
    });
    expect(printed).toBe(`// Generated by rust-js from lib.rs. Do not edit.

import type { NamedExoticComponent, ReactNode } from "react";

export interface Props extends Omit<Anchor, "href"> {
    size?: (string | undefined)[];
}

export default Props;
`);
  } finally {
    await ts.close();
  }
});

// A member's name TypeScript reads as an identifier is written as it is, a
// non-ASCII one too; any other is quoted (#582).
test("print writes a name that's an identifier as it is, and quotes any other", async () => {
  const ts = await open();
  try {
    const names = ["名𠀀é", "$value", "_a1", "aria-label", "1st", ""];
    const printed = await ts.print({
      header: "",
      declarations: [
        {
          kind: "interface",
          name: "Names",
          exported: true,
          declare: false,
          typeParameters: [],
          extends: [],
          members: names.map((name) => ({ kind: "property", name, optional: false, readonly: false, type: { kind: "keyword", keyword: "number" } })),
        },
      ],
    });
    expect(printed).toBe(`export interface Names {
    名𠀀é: number;
    $value: number;
    _a1: number;
    "aria-label": number;
    "1st": number;
    "": number;
}
`);
  } finally {
    await ts.close();
  }
});

// A conditional type, and a type alias of an object whose members carry
// their doc comments, as an interface's do: a type map's lookup and its
// map (ADR 1164).
test("print writes a conditional type, and an object alias's members' docs", async () => {
  const ts = await open();
  try {
    const reference = (name: string) => ({ kind: "reference" as const, name, args: [] });
    const printed = await ts.print({
      header: "",
      declarations: [
        {
          kind: "type",
          name: "Vocabulary",
          exported: true,
          declare: false,
          typeParameters: [],
          type: {
            kind: "object",
            members: [{ kind: "property", name: "escape-key", optional: false, readonly: false, type: reference("KeyboardEvent"), docs: "/** Escape. */" }],
          },
        },
        {
          kind: "type",
          name: "EventOf",
          exported: true,
          declare: false,
          typeParameters: [{ name: "Reason", constraint: { kind: "keyword", keyword: "string" }, default: { kind: "keyword", keyword: "string" } }],
          type: {
            kind: "conditional",
            check: reference("Reason"),
            extends: { kind: "keyof", type: reference("Vocabulary") },
            whenTrue: { kind: "indexed", object: reference("Vocabulary"), index: reference("Reason") },
            whenFalse: reference("Event"),
          },
        },
        {
          kind: "type",
          name: "Details",
          exported: true,
          declare: false,
          typeParameters: [{ name: "R" }],
          type: {
            kind: "conditional",
            check: reference("R"),
            extends: { kind: "keyword", keyword: "unknown" },
            whenTrue: { kind: "object", members: [{ kind: "property", name: "reason", optional: false, readonly: false, type: reference("R"), docs: "/** Why. */" }] },
            whenFalse: { kind: "keyword", keyword: "never" },
          },
        },
      ],
    });
    expect(printed).toBe(`export type Vocabulary = {
    /** Escape. */
    "escape-key": KeyboardEvent;
};

export type EventOf<Reason extends string = string> = Reason extends keyof Vocabulary ? Vocabulary[Reason] : Event;

export type Details<R> = R extends unknown ? {
    /** Why. */
    reason: R;
} : never;
`);
  } finally {
    await ts.close();
  }
});

// A union with `unknown` or `any` is that keyword, as TypeScript reads it:
// an `Option<&Unknown>`'s `unknown | null | undefined` is `unknown`, an
// array of them `unknown[]` (#1850).
test("print writes a union with unknown or any as that keyword", async () => {
  const ts = await open();
  try {
    const keyword = (word: string) => ({ kind: "keyword" as const, keyword: word });
    const union = (...words: string[]) => ({ kind: "union" as const, types: words.map(keyword) });
    const alias = (name: string, type: ReturnType<typeof union> | { kind: "array"; element: ReturnType<typeof union>; readonly: boolean }) =>
      ({ kind: "type" as const, name, exported: true, declare: false, typeParameters: [], type });
    const printed = await ts.print({
      header: "",
      declarations: [
        alias("Given", union("unknown", "null", "undefined")),
        alias("Loose", union("string", "any", "unknown")),
        alias("Items", { kind: "array", element: union("unknown", "null"), readonly: false }),
        alias("Kept", union("string", "null")),
      ],
    });
    expect(printed).toBe(`export type Given = unknown;

export type Loose = any;

export type Items = unknown[];

export type Kept = string | null;
`);
  } finally {
    await ts.close();
  }
});

// What react's generator reads (ADR 0207): React's own element attributes.
test("read takes @types/react's element attributes apart", async () => {
  const file = join(root, "node_modules/@types/react/index.d.ts");
  const ts = await open([file]);
  try {
    const { declarations: read } = await ts.read(file);
    const react = read.find((d) => d.kind === "namespace" && d.name === "React");
    const anchor = react?.kind === "namespace" ? react.declarations.find((d) => d.kind === "interface" && d.name === "AnchorHTMLAttributes") : undefined;
    expect(anchor).toMatchObject({ extends: [{ kind: "reference", name: "HTMLAttributes", args: [{ kind: "reference", name: "T" }] }] });
    expect(anchor?.kind === "interface" && anchor.members.find((m) => m.kind === "property" && m.name === "href")).toMatchObject({ optional: true });
  } finally {
    await ts.close();
  }
}, underLoad(60_000));

// The model has no type-only name among values, so a list that names one is
// text: @types/node's `export { type AllowSharedBuffer, Buffer }`. A list of
// types alone is a type-only export, `export type { ReactTestInstance }`, a
// class's type without its value (ADR 0761, amended).
test("read keeps an export list that names a type as text", async () => {
  const file = join(fixture("typescript-export-types"), "buffer.d.ts");
  writeFileSync(file, "type A = 1;\ndeclare const B: 2;\nexport { type A, B };\nexport { B as C };\nexport type { A as D };\n");
  const ts = await open([file]);
  try {
    const { declarations: read } = await ts.read(file);
    expect(read.slice(2)).toEqual([
      { kind: "other", text: "export { type A, B };" },
      { kind: "export", names: [["B", "C"]] },
      { kind: "export", names: [["A", "D"]], typeOnly: true },
    ]);
    expect(await ts.print({ declarations: read.slice(3) })).toBe("export { B as C };\n\nexport type { A as D };\n");
  } finally {
    await ts.close();
  }
});

// What it prints is erasable syntax only, TypeScript's `erasableSyntaxOnly`
// (ADR 0206): types, which TypeScript checks as a .ts file's, and no
// namespace of values, which it refuses to print.
test("print writes erasable syntax only", async () => {
  const dir = fixture("typescript-erasable");
  const ts = await open();
  try {
    const types = await ts.print({
      declarations: [
        { kind: "import", from: "./other", names: ["Other"], typeOnly: true },
        { kind: "type", name: "Size", exported: true, declare: false, typeParameters: [], type: { kind: "union", types: [{ kind: "literal", value: "md" }, { kind: "literal", value: "lg" }] } },
        { kind: "interface", name: "Props", exported: true, declare: false, typeParameters: [], extends: [{ kind: "reference", name: "Other", args: [] }], members: [{ kind: "property", name: "size", optional: true, readonly: false, type: { kind: "reference", name: "Size", args: [] } }] },
        { kind: "namespace", name: "Types", exported: true, declare: false, declarations: [{ kind: "type", name: "Inner", exported: true, declare: false, typeParameters: [], type: { kind: "keyword", keyword: "string" } }] },
      ],
    });
    writeFileSync(join(dir, "other.ts"), "export interface Other { id?: string }\n");
    writeFileSync(join(dir, "types.ts"), types);
    writeFileSync(join(dir, "tsconfig.json"), JSON.stringify({ compilerOptions: { strict: true, noEmit: true, erasableSyntaxOnly: true, verbatimModuleSyntax: true, module: "esnext", moduleResolution: "bundler" }, files: ["types.ts"] }));
    const checked = Bun.spawnSync([process.execPath, join(root, "node_modules/typescript/bin/tsc"), "-p", join(dir, "tsconfig.json")], { cwd: dir });
    expect(checked.stdout.toString()).toBe("");
    const values = { kind: "namespace" as const, name: "Values", exported: true, declare: false, declarations: [{ kind: "const" as const, name: "x", exported: true, declare: false, type: { kind: "keyword" as const, keyword: "number" } }] };
    expect(ts.print({ declarations: [values] })).rejects.toThrow("isn't erasable");
    expect(await ts.print({ declarations: [{ ...values, declare: true }] })).toContain("declare namespace Values");
  } finally {
    await ts.close();
  }
});

// Construct signatures are callable with new; a method named "new" is not.
test("construct signatures retain generics and optional/rest arguments in every member position", async () => {
  const dir = fixture("typescript-construct");
  const file = join(dir, "construct.d.ts");
  writeFileSync(file, `export interface Factory {
    new <T extends object>(value: T, label?: string, ...rest: number[]): T;
    "new"(): string;
}

export type Nested = {
    new (value?: string): Factory;
};
`);
  const ts = await open([file]);
  try {
    const model = await ts.read(file);
    const factory = model.declarations[0];
    expect(factory).toMatchObject({kind: "interface", members: [
      {kind: "construct", typeParameters: [{name: "T", constraint: {kind: "keyword", keyword: "object"}}], params: [
        {name: "value", optional: false, rest: false},
        {name: "label", optional: true, rest: false},
        {name: "rest", optional: false, rest: true},
      ], returns: {kind: "reference", name: "T"}},
      {kind: "method", name: "new"},
    ]});
    expect(model.declarations[1]).toMatchObject({kind: "type", type: {kind: "object", members: [{kind: "construct", params: [{optional: true}], returns: {kind: "reference", name: "Factory"}}]}});
    if (factory.kind !== "interface") throw new Error("expected the factory interface");
    expect(checkedMembers(factory.members)).toBe(factory.members);
    expect(() => checkedMembers([{kind: "future-member"}] as any)).toThrow("isn't one TypeScript is given");
    const printed = await ts.print(model);
    expect(printed).toBe(await Bun.file(file).text());
    const again = join(dir, "again.d.ts");
    writeFileSync(again, printed);
    const reopened = await open([again]);
    try { expect(await reopened.read(again)).toEqual(model); }
    finally { await reopened.close(); }
    await expect(ts.print({declarations: [{...factory, members: [{kind: "unrecognized-member"}]}]} as any)).rejects.toThrow("isn't one TypeScript is given");
  } finally { await ts.close(); }
});
