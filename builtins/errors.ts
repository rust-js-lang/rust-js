// Writes src/errors.rs: JS's standard errors of a kind, ECMAScript's
// NativeError constructors, `RangeError`, `TypeError` and the others (ADR
// 0283). Each is an `Error` of one shape, made as `new Error(message,
// options)` is, its class its own: an object a program makes of one is that
// class's, `instanceof RangeError`, as JS's own are. The shape is written
// here once, of the six the standard names; `Error` and `AggregateError`,
// each of a shape of its own, are written by hand in src/lib.rs.
//
//   bun builtins/errors.ts [out]   writes src/errors.rs, or `out`

import { snake } from "../scripts/rust-names";

/** Each NativeError, ECMAScript's order, and what JS throws one of. */
const ERRORS: [string, string][] = [
  ["EvalError", "the global `eval()`, which JS no longer throws, kept for what reads one"],
  ["RangeError", "a value outside the set or range it may be, an array's length below zero"],
  ["ReferenceError", "a variable read that doesn't exist, or isn't made yet"],
  ["SyntaxError", "code or text that isn't valid, what `JSON.parse` throws of what isn't JSON"],
  ["TypeError", "a value not of the type an operation takes, a call of what isn't a function"],
  ["URIError", "a URI's function used wrongly, what `decodeURIComponent` throws of a malformed one"],
];

const page = (path: string) => `https://developer.mozilla.org/docs/Web/JavaScript/Reference/Global_Objects/${path}`;

const out: string[] = [];
const line = (s = "") => out.push(s);

line("//! JS's standard errors of a kind (ADR 0283): `RangeError`, `TypeError` and");
line("//! the others ECMAScript names, each an [`Error`] by `Deref`, declared its");
line("//! class, and made by its module's `new`, `range_error::new(message,");
line("//! options)`, `new RangeError(message, options)`, whose object is that");
line("//! class's, `instanceof RangeError`, as JS's own are.");
line("//! Generated by `builtins/errors.ts`; edit the shape there.");
line();
line("use super::{Error, ErrorOptions, JsObject};");
line("use core::marker::PhantomData;");
line();
for (const [name, what] of ERRORS) {
  const module = snake(name);
  line(`/// [\`${name}\`](${page(name)}):`);
  line(`/// an \`Error\` of ${what}.`);
  line(`/// It's a \`&Error\` by \`Deref\`, declared \`${name}\`.`);
  line(`#[cfg_attr(rust_js, rust_js::types = ${JSON.stringify(name)})]`);
  line(`pub struct ${name}(PhantomData<JsObject>);`);
  line();
  line(`impl core::ops::Deref for ${name} {`);
  line("    type Target = Error;");
  line();
  line("    fn deref(&self) -> &Error {");
  line("        // Never runs: rust-js compiles this `Deref` to the object itself.");
  line("        unsafe { &*(self as *const Self as *const Error) }");
  line("    }");
  line("}");
  line();
  line(`pub mod ${module} {`);
  line("    use super::*;");
  line();
  line(`    /// [\`new ${name}(message, options)\`](${page(`${name}/${name}`)}):`);
  line(`    /// one of \`message\`, to throw or to reject a promise with, as`);
  line(`    /// TypeScript's \`message?: string\`: of \`None\`, \`new ${name}()\`, which has no`);
  line(`    /// \`message\` of its own; of \`options\`, its \`cause\`, or \`None\`, left out.`);
  line(`    /// As a value it's \`${name}\` itself, which JS makes the same \`${name}\``);
  line("    /// called without `new`, as `error::new`'s is (rd404).");
  line(`    #[cfg_attr(rust_js, rust_js::link_name = ${JSON.stringify(`new ${name}`)})]`);
  line("    #[cfg_attr(rust_js, rust_js::called_constructs)]");
  line(`    pub fn new(message: Option<&str>, options: Option<&ErrorOptions<'_>>) -> &'static ${name} {`);
  line("        unreachable!()");
  line("    }");
  line("}");
  if (name !== ERRORS[ERRORS.length - 1][0]) line();
}

await Bun.write(process.argv[2] ?? new URL("./src/errors.rs", import.meta.url), `${out.join("\n")}\n`);
